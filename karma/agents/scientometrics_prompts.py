RELATIONSHIP = COMMON + """
仅抽取输入实体之间有明确证据支持的直接关系。端点名称必须与实体清单完全一致，
实体清单本身不构成文本证据。允许的关系使用以下小写标签，并严格遵守方向。

论文关系（Paper → Indicator）：
- proposes：该论文首次提出、命名或正式定义一个新指标。
  复述已有定义或引用源头文献不构成 proposes。
- modifies：该论文实际修正、扩展、加权、归一化已有指标，或调整时间窗口、适用对象。
  清单中存在修改后有名称的变体时，优先以该变体作为 tail，不得编造变体。
  仅引用他人的修改不构成本文修改。
- applies：该论文将已有指标实际用于实证分析、案例研究、评价或方法比较。
  仅在背景中提及或建议使用不构成 applies。
对每个 Paper/Indicator 对，只选择一个有证据支持的主关系，优先级为proposes > modifies > applies。
不得把被引作者的贡献归于当前论文。实体清单中标记为 Paper 的节点由程序提供，
代表当前论文，其名称为元数据标题，标题缺失时为 DOI，无需在摘要中重新找到该名称。
本文作者的“我们”“本文”等表述可指向该 Paper，但关系成立仍须有正文证据。
未提供 Paper 节点时不输出论文关系；不得自行生成论文端点。

指标关系（Indicator A → Indicator B）：
- variant_of：A 明确保留 B 的核心思想或公式结构，但改变参数、权重、归一化方式、
  时间窗口或适用对象。
- derived_from：A 明确直接来源于 B，但存在超出简单变体的实质性改动。
  同一方向不得同时输出 variant_of 和 derived_from。
- improves_on：A 明确针对 B 的某项局限性、偏差或适用性问题提出改进。
  证据中必须保留这是设计目标还是已观察到的结果，以及成立条件。
  仅凭指标新颖或数值较高不能判定改进。
- alternative_to：A、B 在明确条件下针对共同评价目标构成替代或竞争方案。
  仅共同出现、一起比较或数值相关不足以证明可替代。
  该关系对称，每对仅输出一次，以输入清单中靠前的实体作为 head。
- component_of：A 作为输入指标或组成指标纳入复合指标/评价框架 B。
  方向为部分 → 整体，两端都必须是清单中已有的 Indicator 实体。

禁止自关系、虚构端点、补充传递关系或生成反向重复关系。
不同关系标签只有各自存在独立依据时才能并存。缺乏依据时直接省略。
每个 evidence 必须是输入摘要中逐字摘录的一段连续文本，不得改写解释或拼接多个引句。
不得声称已对照原始 PDF 页面核验。缺少必要证据或归属信息时不输出该关系。
confidence 范围为 [0,1]，表示证据清晰程度，不代表事实真实性或指标质量。
仅返回包含 head、relation、tail、confidence、evidence 字段的 JSON 对象数组，例如：
[{"head":"A-index","relation":"variant_of","tail":"B-index","confidence":0.9,
"evidence":"A-index is a time-window variant of B-index."}]
上述例子仅说明格式，不能作为实际输入的证据。没有符合条件的关系时返回 []。
"""

